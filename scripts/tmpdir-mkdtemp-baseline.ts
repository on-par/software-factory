// RATCHET (#3114): test files that still call mkdtemp directly on os.tmpdir().
// The per-run TMPDIR sandbox (scripts/test-tmp-sandbox.ts) keeps these from leaking, but
// new code must use createTempDirs from @on-par/factory-core/testing. Entries may only shrink.

const DIRECT_JOIN = /\bmkdtemp(?:Sync)?\(\s*(?:path\.)?join\(\s*(?:os\.)?tmpdir\(\)/g;
const DIRECT_BARE = /\bmkdtemp(?:Sync)?\(\s*(?:os\.)?tmpdir\(\)/g;

export function countDirectTmpdirMkdtemp(source: string): number {
  return (source.match(DIRECT_JOIN)?.length ?? 0) + (source.match(DIRECT_BARE)?.length ?? 0);
}

