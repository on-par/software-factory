// packages/cli/src/cli/runner.ts — factory daemon runner install|uninstall|list: supported per-repo runner LaunchAgents (#2282).

import {
  chmodSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';

import { getFactoryPaths } from '@on-par/factory-core';
import { listRepos, loadRegistry } from '@on-par/factory-core/internal';

import {
  DaemonCtlError,
  parseLaunchctlPid,
  requireDarwin,
  resolveDeps,
  xmlEscape,
  type DaemonCtlDeps,
} from './daemon.js';

export const RUNNER_LABEL_PREFIX = 'com.onpar.factory-';
export const RUNNER_LOOP_SLEEP_SEC = 90;

/** On-disk record of a runner the CLI installed; the source of truth for list and uninstall. */
export interface RunnerManifest {
  schemaVersion: 1;
  label: string;
  name: string;
  checkout: string;
  plist: string;
  script: string;
  log: string;
  env: Record<string, string>;
  installedAt: string;
}

export type RunnerInstallJson =
  { ok: true; label: string; plist: string; script: string } | { ok: false; label: string | null; error: string };

/** `factory daemon runner list --json` payload. Additive changes only; bump schemaVersion on a breaking change. */
export interface RunnerListJson {
  schemaVersion: 1;
  runners: Array<{
    label: string;
    checkout: string;
    plist: string;
    script: string;
    log: string;
    running: boolean;
    pid: number | null;
  }>;
}

export function runnerFiles(
  home: string,
  name: string,
): { label: string; plistPath: string; scriptPath: string; manifestPath: string } {
  const label = `${RUNNER_LABEL_PREFIX}${name}`;
  const runnersDir = join(home, '.factory', 'runners');
  return {
    label,
    plistPath: join(home, 'Library', 'LaunchAgents', `${label}.plist`),
    scriptPath: join(runnersDir, `factory-${name}-run.sh`),
    manifestPath: join(runnersDir, `factory-${name}.json`),
  };
}

/** Returns the runner *name* (label minus the com.onpar.factory- prefix). Throws code 2 when empty. */
export function normalizeRunnerLabel(raw: string | undefined, repoRoot: string): string {
  let name = (raw ?? basename(repoRoot)).trim();
  if (name.startsWith(RUNNER_LABEL_PREFIX)) name = name.slice(RUNNER_LABEL_PREFIX.length);
  name = name
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, '-')
    .replace(/^[-.]+|[-.]+$/g, '');
  if (!name) throw new DaemonCtlError(`invalid --label "${raw ?? ''}" — expected letters, digits, ".", "_" or "-"`, 2);
  return name;
}

export function parseRunnerEnv(pairs: string[] | undefined): Record<string, string> {
  const env: Record<string, string> = {};
  for (const p of pairs ?? []) {
    const eq = p.indexOf('=');
    const key = eq < 0 ? '' : p.slice(0, eq);
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) {
      throw new DaemonCtlError(`invalid --env "${p}" — expected KEY=VALUE`, 2);
    }
    env[key] = p.slice(eq + 1);
  }
  return env;
}

export function renderRunnerPlist(opts: {
  label: string;
  scriptPath: string;
  checkout: string;
  logPath: string;
}): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${xmlEscape(opts.label)}</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/bash</string>
    <string>${xmlEscape(opts.scriptPath)}</string>
  </array>
  <key>WorkingDirectory</key>
  <string>${xmlEscape(opts.checkout)}</string>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>StandardOutPath</key>
  <string>${xmlEscape(opts.logPath)}</string>
  <key>StandardErrorPath</key>
  <string>${xmlEscape(opts.logPath)}</string>
</dict>
</plist>
`;
}

/** Single-quote shell escaping. */
function q(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

export function renderRunnerScript(opts: {
  checkout: string;
  nodePath: string;
  cliScriptPath: string;
  logPath: string;
  env: Record<string, string>;
}): string {
  const exports = Object.keys(opts.env)
    .sort()
    .map((k) => `export ${k}=${q(opts.env[k] ?? '')}`)
    .join('\n');
  return `#!/bin/bash
# generated by factory daemon runner install — do not edit; reinstall instead
set -u
cd ${q(opts.checkout)} || exit 1
${exports}${exports ? '\n' : ''}LOG=${q(opts.logPath)}
mkdir -p "$(dirname "$LOG")"
while true; do
  echo "[runner] $(date -u +%Y-%m-%dT%H:%M:%SZ) factory run starting" >> "$LOG"
  ${q(opts.nodePath)} ${q(opts.cliScriptPath)} run >> "$LOG" 2>&1
  rc=$?
  echo "[runner] $(date -u +%Y-%m-%dT%H:%M:%SZ) factory run exited $rc; sleeping ${RUNNER_LOOP_SLEEP_SEC}s" >> "$LOG"
  sleep ${RUNNER_LOOP_SLEEP_SEC}
done
`;
}

function readManifest(path: string): RunnerManifest | null {
  try {
    const m = JSON.parse(readFileSync(path, 'utf8')) as RunnerManifest;
    return m && typeof m.label === 'string' && typeof m.checkout === 'string' ? m : null;
  } catch {
    return null;
  }
}

function readManifests(home: string): RunnerManifest[] {
  const dir = join(home, '.factory', 'runners');
  let names: string[];
  try {
    names = readdirSync(dir);
  } catch {
    return [];
  }
  return names
    .filter((n) => n.endsWith('.json'))
    .sort()
    .map((n) => readManifest(join(dir, n)))
    .filter((m): m is RunnerManifest => m !== null);
}

function safeRealpath(p: string): string {
  try {
    return realpathSync(p);
  } catch {
    return resolve(p);
  }
}

/** With --json, a DaemonCtlError becomes one {ok:false} object and the exit code; otherwise rethrown. */
function jsonFailure(
  d: { out: { write(s: string): unknown } },
  err: unknown,
  label: string | null,
  json: boolean | undefined,
): void {
  if (!json || !(err instanceof DaemonCtlError)) throw err;
  const payload: RunnerInstallJson = { ok: false, label, error: err.message };
  d.out.write(`${JSON.stringify(payload)}\n`);
  process.exitCode = err.code;
}

export async function cmdRunnerInstall(
  repoRoot: string,
  opts: { label?: string; env?: string[]; json?: boolean },
  deps: DaemonCtlDeps = {},
): Promise<void> {
  const d = resolveDeps(deps);
  requireDarwin(d.platform, 'factory daemon runner');
  let label: string | null = null;
  try {
    const checkout = realpathSync(repoRoot);
    const name = normalizeRunnerLabel(opts.label, checkout);
    const files = runnerFiles(d.home, name);
    label = files.label;
    const userEnv = parseRunnerEnv(opts.env);

    for (const repo of listRepos(await loadRegistry(d.registryFile))) {
      if (repo.state !== 'detached' && safeRealpath(repo.path) === checkout) {
        throw new DaemonCtlError(
          `${checkout} is already managed by factoryd (${repo.slug}); one supervisor per repo — detach it first`,
          1,
        );
      }
    }
    const existing = readManifests(d.home).find((m) => m.checkout === checkout);
    if (existing) {
      throw new DaemonCtlError(`${checkout} already has a runner (${existing.label}); uninstall it first`, 1);
    }
    if (existsSync(files.plistPath) || existsSync(files.manifestPath)) {
      throw new DaemonCtlError(
        `${files.plistPath} already exists; refusing to overwrite (uninstall it first, or pick another --label)`,
        1,
      );
    }

    const log = join(getFactoryPaths(checkout).state, 'runner.log');
    const stateRoot = d.env.FACTORY_STATE_ROOT;
    const env: Record<string, string> = {
      PATH: d.env.PATH ?? '/usr/bin:/bin',
      HOME: d.home,
      ...(stateRoot ? { FACTORY_STATE_ROOT: stateRoot } : {}),
      ...userEnv,
    };

    mkdirSync(dirname(files.plistPath), { recursive: true });
    mkdirSync(dirname(files.scriptPath), { recursive: true });
    mkdirSync(dirname(log), { recursive: true });
    writeFileSync(
      files.scriptPath,
      renderRunnerScript({ checkout, nodePath: d.nodePath, cliScriptPath: d.cliScriptPath, logPath: log, env }),
      { mode: 0o755 },
    );
    chmodSync(files.scriptPath, 0o755);
    writeFileSync(
      files.plistPath,
      renderRunnerPlist({ label: files.label, scriptPath: files.scriptPath, checkout, logPath: log }),
    );
    const manifest: RunnerManifest = {
      schemaVersion: 1,
      label: files.label,
      name,
      checkout,
      plist: files.plistPath,
      script: files.scriptPath,
      log,
      env,
      installedAt: new Date().toISOString(),
    };
    writeFileSync(files.manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

    await d.exec('launchctl', ['bootout', `gui/${d.uid}/${files.label}`]);
    const boot = await d.exec('launchctl', ['bootstrap', `gui/${d.uid}`, files.plistPath]);
    if (boot.code !== 0) {
      throw new DaemonCtlError(
        `launchctl bootstrap failed: ${boot.stderr.trim() || boot.stdout.trim() || `exit ${boot.code}`}`,
        1,
      );
    }
    const print = await d.exec('launchctl', ['print', `gui/${d.uid}/${files.label}`]);
    const pid = parseLaunchctlPid(print.stdout);

    if (opts.json) {
      const payload: RunnerInstallJson = {
        ok: true,
        label: files.label,
        plist: files.plistPath,
        script: files.scriptPath,
      };
      d.out.write(`${JSON.stringify(payload)}\n`);
      return;
    }
    d.out.write(`runner: installed ${files.plistPath}\n`);
    d.out.write(`runner: script ${files.scriptPath}\n`);
    d.out.write(`runner: log ${log}\n`);
    d.out.write(
      pid === null ? 'runner: loaded — launchd will start it (RunAtLoad)\n' : `runner: running (pid ${pid})\n`,
    );
  } catch (err) {
    jsonFailure(d, err, label, opts.json);
  }
}

export async function cmdRunnerUninstall(
  repoRoot: string,
  opts: { label?: string; json?: boolean },
  deps: DaemonCtlDeps = {},
): Promise<void> {
  const d = resolveDeps(deps);
  requireDarwin(d.platform, 'factory daemon runner');
  let label: string | null = null;
  try {
    const name = normalizeRunnerLabel(opts.label, safeRealpath(repoRoot));
    const files = runnerFiles(d.home, name);
    label = files.label;
    const manifest = readManifest(files.manifestPath);
    if (!manifest) {
      throw new DaemonCtlError(`no factory-installed runner ${files.label} (hand-rolled runners are not managed)`, 1);
    }
    await d.exec('launchctl', ['bootout', `gui/${d.uid}/${files.label}`]);
    rmSync(files.plistPath, { force: true });
    rmSync(files.scriptPath, { force: true });
    rmSync(files.manifestPath, { force: true });
    if (opts.json) {
      const payload: RunnerInstallJson = {
        ok: true,
        label: files.label,
        plist: files.plistPath,
        script: files.scriptPath,
      };
      d.out.write(`${JSON.stringify(payload)}\n`);
      return;
    }
    d.out.write(`runner: uninstalled ${files.label}\n`);
  } catch (err) {
    jsonFailure(d, err, label, opts.json);
  }
}

export async function cmdRunnerList(opts: { json?: boolean }, deps: DaemonCtlDeps = {}): Promise<void> {
  const d = resolveDeps(deps);
  requireDarwin(d.platform, 'factory daemon runner');
  const manifests = readManifests(d.home).sort((a, b) => a.label.localeCompare(b.label));
  const runners: RunnerListJson['runners'] = [];
  for (const m of manifests) {
    const print = await d.exec('launchctl', ['print', `gui/${d.uid}/${m.label}`]);
    const pid = print.code === 0 ? parseLaunchctlPid(print.stdout) : null;
    runners.push({
      label: m.label,
      checkout: m.checkout,
      plist: m.plist,
      script: m.script,
      log: m.log,
      running: pid !== null,
      pid,
    });
  }
  if (opts.json) {
    const payload: RunnerListJson = { schemaVersion: 1, runners };
    d.out.write(`${JSON.stringify(payload)}\n`);
    return;
  }
  if (runners.length === 0) {
    d.out.write('runners: none\n');
    return;
  }
  for (const r of runners) {
    d.out.write(`${r.label} ${r.running ? `running (pid ${r.pid})` : 'not running'} ${r.checkout}\n`);
  }
}
